// A Markdown wiki in the spirit of Karpathy's LLM wiki, opened in Obsidian, Zed or any editor:
// one note per item, a page per project, a source table, an index. It is a compiled view:
// regenerated whole from the ledger on every run, never edited, never the store.

import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { GradedItem, ViewSink } from "../core/types.ts";
import { clip, slug } from "../core/text.ts";

const MARKER = ".swb-feed-view";

/** What this view generates, and the only paths it ever removes. */
const GENERATED = ["notes", "projects", "index.md", "sources.md"];

/**
 * Refuses a non-empty directory it did not create. Inside its own directory it replaces only
 * what it generates, so an editor's config (.obsidian/) or your own notes beside it survive.
 */
export function claimViewDir(dir: string): void {
  mkdirSync(dir, { recursive: true });
  const entries = readdirSync(dir).filter((e) => !e.startsWith("."));
  if (entries.length > 0 && !existsSync(join(dir, MARKER))) {
    throw new Error(`${dir} is not empty and was not created by swb-feed; refusing to overwrite it`);
  }
  for (const e of GENERATED) rmSync(join(dir, e), { recursive: true, force: true });
  writeFileSync(join(dir, MARKER), "generated by swb-feed: notes/, projects/, index.md and sources.md are rebuilt from the ledger\n");
}

export function noteName(i: GradedItem): string {
  return `${(i.published_at ?? i.captured_at).slice(0, 10)}-${slug(i.title, 50)}-${i.id.slice(0, 6)}`;
}

const yamlStr = (s: string) => JSON.stringify(s);
const yamlList = (xs: string[]) => `[${xs.map(yamlStr).join(", ")}]`;

function note(i: GradedItem): string {
  const g = i.grade;
  return [
    "---",
    `id: ${i.id}`,
    `title: ${yamlStr(i.title)}`,
    i.url ? `url: ${i.url}` : null,
    `source: ${yamlStr(i.source)}`,
    i.author ? `author: ${yamlStr(i.author)}` : null,
    i.published_at ? `published: ${i.published_at}` : null,
    `captured: ${i.captured_at}`,
    `kind: ${i.content_kind}`,
    `score: ${g.score}`,
    g.tier ? `tier: ${g.tier}` : null,
    g.quality !== undefined ? `quality: ${g.quality}` : null,
    g.importance !== undefined ? `importance: ${g.importance}` : null,
    g.novelty !== undefined ? `novelty: ${g.novelty}` : null,
    g.urgency !== undefined ? `urgency: ${g.urgency}` : null,
    `labels: ${yamlList(g.labels)}`,
    `projects: ${yamlList(g.projects)}`,
    `rules: ${yamlList(i.rules)}`,
    `priority: ${i.priority}`,
    `grader: ${g.grader}`,
    `profile: ${g.profile_hash}`,
    "---",
    "",
    `# ${i.title}`,
    "",
    `> ${g.summary_short}`,
    "",
    `**Score ${g.score}**${g.tier ? ` · tier ${g.tier} · quality ${g.quality ?? "?"}` : ""} · ${i.source}${i.author ? ` · ${i.author}` : ""}${g.projects.length ? ` · ${g.projects.map((p) => `[[projects/${slug(p)}|${p}]]`).join(" ")}` : ""}`,
    "",
    "## Why it is here",
    "",
    ...g.why.map((w) => `- ${w}`),
    "",
    "## Summary",
    "",
    g.summary_medium,
    "",
    "## Excerpt",
    "",
    clip(i.content, 1800),
    "",
    i.url ? `Source: <${i.url}>` : "",
    "",
  ]
    .filter((l) => l !== null)
    .join("\n");
}

const row = (i: GradedItem) =>
  `| ${i.grade.score} | [[notes/${noteName(i)}\\|${clip(i.title, 70).replace(/\|/g, "/")}]] | ${i.source} | ${(i.published_at ?? i.captured_at).slice(0, 10)} |`;

export function wiki(o: { dir: string; title?: string }): ViewSink {
  return {
    kind: "view",
    async render(items, ctx) {
      if (ctx.dryRun) return { ref: o.dir };
      claimViewDir(o.dir);
      mkdirSync(join(o.dir, "notes"), { recursive: true });
      mkdirSync(join(o.dir, "projects"), { recursive: true });
      const sorted = [...items].sort((a, b) => b.grade.score - a.grade.score || b.captured_at.localeCompare(a.captured_at));
      for (const i of sorted) writeFileSync(join(o.dir, "notes", `${noteName(i)}.md`), note(i));

      const byProject = new Map<string, GradedItem[]>();
      for (const i of sorted) for (const p of i.grade.projects) byProject.set(p, [...(byProject.get(p) ?? []), i]);
      for (const [p, list] of byProject) {
        writeFileSync(
          join(o.dir, "projects", `${slug(p)}.md`),
          [`# ${p}`, "", `${list.length} items the feed matched to this project, best first.`, "", "| Score | Item | Source | Date |", "|---|---|---|---|", ...list.map(row), ""].join("\n"),
        );
      }

      const bySource = new Map<string, GradedItem[]>();
      for (const i of sorted) bySource.set(i.source, [...(bySource.get(i.source) ?? []), i]);
      const sourceRows = [...bySource]
        .map(([s, l]) => ({ s, n: l.length, avg: Math.round(l.reduce((a, i) => a + i.grade.score, 0) / l.length), top: l[0] }))
        .sort((a, b) => b.avg - a.avg)
        .map((r) => `| ${r.s} | ${r.n} | ${r.avg} | [[notes/${noteName(r.top)}\\|${clip(r.top.title, 50).replace(/\|/g, "/")}]] |`);
      writeFileSync(
        join(o.dir, "sources.md"),
        ["# Sources", "", "Which sources earn their place: average score against the intent profile.", "", "| Source | Items | Avg score | Best item |", "|---|---|---|---|", ...sourceRows, ""].join("\n"),
      );

      writeFileSync(
        join(o.dir, "index.md"),
        [
          `# ${o.title ?? "Brain"}`,
          "",
          `${sorted.length} items · ${byProject.size} projects · ${bySource.size} sources · rebuilt ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC from the ledger.`,
          "",
          "## By project",
          "",
          ...[...byProject].sort((a, b) => b[1].length - a[1].length).map(([p, l]) => `- [[projects/${slug(p)}|${p}]] (${l.length}): ${clip(l[0].title, 70)}`),
          "",
          "## Top items",
          "",
          "| Score | Item | Source | Date |",
          "|---|---|---|---|",
          ...sorted.slice(0, 25).map(row),
          "",
          "See also [[sources]].",
          "",
        ].join("\n"),
      );
      return { ref: o.dir };
    },
  };
}
